#[test]
fn test_end_to_end_document_classification_and_enrichment() {
    let doc = build_polyglot_test_document();
    let config = ClassificationConfig::default();

    let (enriched_doc, report) = classify_document(&doc, &config);

    assert_eq!(enriched_doc.sections.len(), 11);
    assert_eq!(report.total_sections, 11);
    assert!(report.total_tokens > 0);
    assert!(report.total_bytes > 0);

    // Cryptographic hash preservation: section content hashes must remain completely valid!
    assert!(enriched_doc.verify_section_hashes());

    // Verify attribute enrichment across sections
    let rust_sec = enriched_doc
        .sections
        .iter()
        .find(|s| s.section_id == "sec-rust-prod")
        .unwrap();
    assert_eq!(
        rust_sec.attributes.get("content_category").unwrap(),
        "source_code"
    );
    assert_eq!(
        rust_sec.attributes.get("information_density").unwrap(),
        "high"
    );
    assert_eq!(rust_sec.attributes.get("is_test").unwrap(), "false");
    assert_eq!(rust_sec.attributes.get("is_generated").unwrap(), "false");
    assert!(rust_sec.attributes.contains_key("signal_score"));
    assert!(rust_sec.attributes.contains_key("symbols_summary"));

    let test_sec = enriched_doc
        .sections
        .iter()
        .find(|s| s.section_id == "sec-rust-test")
        .unwrap();
    assert_eq!(
        test_sec.attributes.get("content_category").unwrap(),
        "test_and_verification"
    );
    assert_eq!(test_sec.attributes.get("is_test").unwrap(), "true");

    let gen_sec = enriched_doc
        .sections
        .iter()
        .find(|s| s.section_id == "sec-proto-gen")
        .unwrap();
    assert_eq!(
        gen_sec.attributes.get("content_category").unwrap(),
        "generated_or_boilerplate"
    );
    assert_eq!(gen_sec.attributes.get("is_generated").unwrap(), "true");

    let disc_sec = enriched_doc
        .sections
        .iter()
        .find(|s| s.section_id == "sec-disclaimer")
        .unwrap();
    assert_eq!(
        disc_sec.attributes.get("information_density").unwrap(),
        "trivial"
    );
    assert_eq!(disc_sec.attributes.get("is_boilerplate").unwrap(), "true");
}

#[test]
fn test_classification_report_metrics_and_json_roundtrip() {
    let doc = build_polyglot_test_document();
    let classifier = DocumentContentClassifier::default();
    let (_, report) = classifier.classify_document(&doc);

    assert_eq!(report.document_id, doc.document_id);
    assert_eq!(report.test_section_count, 2); // sec-rust-test and sec-bench
    assert_eq!(report.generated_section_count, 2); // sec-proto-gen and sec-disclaimer
    assert!(report
        .category_counts
        .contains_key(&ContentCategory::SourceCode));
    assert!(report
        .category_counts
        .contains_key(&ContentCategory::Documentation));
    assert!(report
        .category_counts
        .contains_key(&ContentCategory::Specification));
    assert!(report
        .category_counts
        .contains_key(&ContentCategory::DependencyManifest));
    assert!(report
        .category_counts
        .contains_key(&ContentCategory::Configuration));

    // Markdown summary checks
    let md = report.to_markdown_summary();
    assert!(md.contains("### Content Classification Summary"));
    assert!(md.contains(&format!("`{}`", doc.document_id)));
    assert!(md.contains("#### Category Breakdown"));
    assert!(md.contains("| `source_code` |"));
    assert!(md.contains("| `documentation` |"));
    assert!(md.contains("#### Information Density Distribution"));

    // JSON serialization roundtrip
    let json_str = serde_json::to_string_pretty(&report).expect("valid json serialization");
    let deserialized: ContentClassificationReport =
        serde_json::from_str(&json_str).expect("valid json deserialization");
    assert_eq!(report, deserialized);
}

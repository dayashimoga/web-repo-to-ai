#[test]
fn test_generated_and_boilerplate_classification() {
    let config = ClassificationConfig::default();
    let classifier = SectionClassifier::new(&config);

    // 1. Protobuf generated code
    let proto = "// @generated by protobuf. DO NOT EDIT.\nmessage Telemetry { int64 id = 1; }";
    let sec_proto = make_test_section(
        "s-gen",
        "src/gen/telemetry.rs",
        SectionKind::CodeFile,
        "rust",
        proto,
    );
    let class_proto = classifier.classify(&sec_proto);
    assert_eq!(
        class_proto.category,
        ContentCategory::GeneratedOrBoilerplate
    );
    assert!(class_proto.is_generated);
    assert!(class_proto
        .noise_indicators
        .contains(&NoiseIndicator::AutoGeneratedStub));

    // 2. Minified JavaScript bundle
    let minified_chunk = "function a(b){return b*2;}var x=a(10);window.__data=x;";
    let long_minified = minified_chunk.repeat(10);
    let sec_min = make_test_section(
        "s-min",
        "dist/bundle.min.js",
        SectionKind::CodeFile,
        "javascript",
        &long_minified,
    );
    let class_min = classifier.classify(&sec_min);
    assert_eq!(class_min.category, ContentCategory::GeneratedOrBoilerplate);
    assert!(class_min
        .noise_indicators
        .contains(&NoiseIndicator::MinifiedContent));
    assert!(class_min.signal_score <= 0.40);

    // 3. Synthetic license disclaimer
    let disclaimer =
        "// Synthetic Disclaimer Notice for Module Distribution\n// All rights reserved.";
    let sec_disc = make_test_section("s-disc", "LICENSE", SectionKind::Prose, "text", disclaimer);
    let class_disc = classifier.classify(&sec_disc);
    assert_eq!(class_disc.category, ContentCategory::GeneratedOrBoilerplate);
    assert_eq!(class_disc.density, InformationDensity::Trivial);
    assert!(class_disc.is_boilerplate);
    assert!(class_disc
        .noise_indicators
        .contains(&NoiseIndicator::CopyrightHeaderOnly));
}


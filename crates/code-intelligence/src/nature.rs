//! # Code Nature Classification
//!
//! Classifies the role and architectural intent of source code into core implementation,
//! interface definitions, test suites, benchmarks, generated boilerplate, scripts, or schemas.

use serde::{Deserialize, Serialize};

use crate::language::Language;
use crate::symbols::{SymbolDeclaration, SymbolKind};

/// Nature or architectural role of a code segment.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CodeNature {
    /// Primary production implementation or algorithm logic.
    CoreImplementation,
    /// Interface contracts, type definitions, or API declarations.
    InterfaceOrTypeDefinition,
    /// Unit tests, integration tests, assertions, or test fixtures.
    TestOrFixture,
    /// Performance benchmark harnesses or criterion suites.
    Benchmark,
    /// Auto-generated stubs, protocol buffers, or minified artifacts.
    GeneratedOrBoilerplate,
    /// Build specifications, CI scripts, or task runners.
    BuildOrScript,
    /// Database migrations, SQL queries, or data schemas.
    DataOrSchema,
}

impl CodeNature {
    /// Returns the canonical snake_case representation.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::CoreImplementation => "core_implementation",
            Self::InterfaceOrTypeDefinition => "interface_or_type_definition",
            Self::TestOrFixture => "test_or_fixture",
            Self::Benchmark => "benchmark",
            Self::GeneratedOrBoilerplate => "generated_or_boilerplate",
            Self::BuildOrScript => "build_or_script",
            Self::DataOrSchema => "data_or_schema",
        }
    }

    /// Returns true if this code represents test suites or verification fixtures.
    #[must_use]
    pub const fn is_test(self) -> bool {
        matches!(self, Self::TestOrFixture | Self::Benchmark)
    }

    /// Returns true if this code is machine-generated or boilerplate.
    #[must_use]
    pub const fn is_generated_or_boilerplate(self) -> bool {
        matches!(self, Self::GeneratedOrBoilerplate)
    }

    /// Returns true if this code is a core production component.
    #[must_use]
    pub const fn is_core(self) -> bool {
        matches!(
            self,
            Self::CoreImplementation | Self::InterfaceOrTypeDefinition
        )
    }
}

/// Classifies code into a [`CodeNature`].
pub struct CodeNatureClassifier;

impl CodeNatureClassifier {
    /// Classifies code using file path, language, content markers, and extracted symbols.
    #[must_use]
    pub fn classify(
        path: Option<&str>,
        _language: &Language,
        content: &str,
        symbols: &[SymbolDeclaration],
    ) -> CodeNature {
        let normalized_path = path.map(|p| {
            let clean = p.replace('\\', "/").to_ascii_lowercase();
            if clean.starts_with('/') {
                clean
            } else {
                format!("/{clean}")
            }
        });

        // 1. Path-based primary identification
        if let Some(ref p) = normalized_path {
            if is_benchmark_path(p) {
                return CodeNature::Benchmark;
            }
            if is_test_path(p) {
                return CodeNature::TestOrFixture;
            }
            if is_generated_path(p) {
                return CodeNature::GeneratedOrBoilerplate;
            }
            if is_build_or_script_path(p) {
                return CodeNature::BuildOrScript;
            }
            if is_data_or_schema_path(p) {
                return CodeNature::DataOrSchema;
            }
        }

        // 2. Content marker inspection for generated code
        let upper_content = content.to_ascii_uppercase();
        if upper_content.contains("@GENERATED")
            || upper_content.contains("DO NOT EDIT")
            || upper_content.contains("CODE GENERATED BY")
            || upper_content.contains("AUTOGENERATED BY")
            || upper_content.contains("THIS FILE IS GENERATED")
        {
            return CodeNature::GeneratedOrBoilerplate;
        }

        // 3. Content marker inspection for tests
        if content.contains("#[test]")
            || content.contains("#[tokio::test]")
            || content.contains("#[cfg(test)]")
            || content.contains("describe(") && content.contains("it(")
            || content.contains("test(") && content.contains("expect(")
            || content.contains("def test_")
            || content.contains("testing.T")
        {
            return CodeNature::TestOrFixture;
        }

        // 4. Content marker inspection for benchmarks
        if content.contains("criterion_group!")
            || content.contains("b.iter(")
            || content.contains("testing.B")
        {
            return CodeNature::Benchmark;
        }

        // 5. Symbol composition: Interface / Type definition vs Implementation
        if !symbols.is_empty() {
            let type_symbols = symbols
                .iter()
                .filter(|s| s.kind.is_type_definition())
                .count();
            let function_symbols = symbols
                .iter()
                .filter(|s| s.kind == SymbolKind::Function || s.kind == SymbolKind::Method)
                .count();

            // If file consists almost entirely of interfaces/traits/types with no function implementations
            if type_symbols > 0 && function_symbols == 0 {
                return CodeNature::InterfaceOrTypeDefinition;
            }
        }

        // 6. SQL or Schema files
        if content.trim_start().starts_with("CREATE TABLE")
            || content.trim_start().starts_with("ALTER TABLE")
        {
            return CodeNature::DataOrSchema;
        }

        CodeNature::CoreImplementation
    }
}

fn is_benchmark_path(path: &str) -> bool {
    path.contains("/benches/")
        || path.contains("/benchmark/")
        || path.contains("/benchmarks/")
        || path.ends_with("_bench.rs")
        || path.ends_with("_bench.go")
        || path.ends_with(".benchmark.ts")
}

fn is_test_path(path: &str) -> bool {
    path.contains("/tests/")
        || path.contains("/test/")
        || path.contains("/__tests__/")
        || path.contains("/specs/")
        || path.contains("/spec/")
        || path.contains("/fixtures/")
        || path.ends_with("_test.rs")
        || path.ends_with("_test.go")
        || path.ends_with(".test.ts")
        || path.ends_with(".test.js")
        || path.ends_with(".spec.ts")
        || path.ends_with(".spec.js")
        || path
            .rsplit('/')
            .next()
            .map(|f| f.starts_with("test_"))
            .unwrap_or(false)
}

fn is_generated_path(path: &str) -> bool {
    path.contains("/generated/")
        || path.contains("/gen/")
        || path.ends_with(".pb.go")
        || path.ends_with("_grpc.pb.go")
        || path.ends_with(".generated.ts")
        || path.ends_with(".generated.rs")
        || path.ends_with(".min.js")
        || path.ends_with(".min.css")
        || path.ends_with(".map")
}

fn is_build_or_script_path(path: &str) -> bool {
    path.contains("/scripts/")
        || path.contains("/deploy/")
        || path.contains("/.github/")
        || path.ends_with("build.rs")
        || path.ends_with("webpack.config.js")
        || path.ends_with("vite.config.ts")
        || path.ends_with("rollup.config.js")
        || path.ends_with("dockerfile")
}

fn is_data_or_schema_path(path: &str) -> bool {
    path.contains("/migrations/")
        || path.contains("/schema/")
        || path.contains("/schemas/")
        || path.ends_with(".sql")
        || path.ends_with(".schema.json")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_classify_by_path() {
        let rust_lang = Language::Rust;
        assert_eq!(
            CodeNatureClassifier::classify(Some("tests/unit_test.rs"), &rust_lang, "", &[]),
            CodeNature::TestOrFixture
        );
        assert_eq!(
            CodeNatureClassifier::classify(Some("benches/crypto_bench.rs"), &rust_lang, "", &[]),
            CodeNature::Benchmark
        );
        assert_eq!(
            CodeNatureClassifier::classify(Some("scripts/deploy.sh"), &Language::Shell, "", &[]),
            CodeNature::BuildOrScript
        );
        assert_eq!(
            CodeNatureClassifier::classify(
                Some("migrations/001_init.sql"),
                &Language::Sql,
                "",
                &[]
            ),
            CodeNature::DataOrSchema
        );
    }

    #[test]
    fn test_classify_by_content_markers() {
        let rust_lang = Language::Rust;
        let generated_code = "// @generated by protobuf compiler. DO NOT EDIT.\npackage pb;";
        assert_eq!(
            CodeNatureClassifier::classify(Some("src/proto.rs"), &rust_lang, generated_code, &[]),
            CodeNature::GeneratedOrBoilerplate
        );

        let test_code = "fn check_behavior() {\n    #[test]\n    fn test_inner() {}\n}";
        assert_eq!(
            CodeNatureClassifier::classify(Some("src/sub.rs"), &rust_lang, test_code, &[]),
            CodeNature::TestOrFixture
        );
    }
}

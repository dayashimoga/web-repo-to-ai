export interface PreviewFile {
  id: string;
  path: string;
  language: string;
  sizeBytes: number;
  tokenCount: number;
  content: string;
  lineCount?: number;
}

/**
 * Standard token estimation heuristic (~4 chars per token for English & code).
 */
export function estimateTokens(text: string): number {
  if (!text) return 0;
  // BPE average approximation for code and technical text
  return Math.max(1, Math.ceil(text.length / 3.8));
}

/**
 * Formats a list of extracted files into the target export format.
 */
export function formatContentForExport(
  files: PreviewFile[],
  format: PreviewFormat,
  options?: {
    sourceUrl?: string;
    targetFormat?: string;
    modelPreset?: string;
  }
): string {
  const sourceUrl = options?.sourceUrl || "https://github.com/dayashimoga/web-repo-to-ai";
  const now = new Date().toISOString();

  if (files.length === 0) {
    return `# Empty Output\nNo files available in this extraction.`;
  }

  switch (format) {
    case "markdown": {
      const header = [
        `# Context Export: ${sourceUrl}`,
        `> Generated by web-repo-to-ai on ${now}`,
        `> Total Files: ${files.length} | Format: Markdown`,
        ``,
      ].join("\n");

      const body = files
        .map((file) => {
          return [
            `---`,
            `## File: \`${file.path}\``,
            `- **Language:** ${file.language}`,
            `- **Tokens:** ~${file.tokenCount.toLocaleString()} | **Bytes:** ${file.sizeBytes.toLocaleString()} B`,
            ``,
            "```" + file.language,
            file.content,
            "```",
            ``,
          ].join("\n");
        })
        .join("\n");

      return `${header}\n${body}`;
    }

    case "json": {
      const totalTokens = files.reduce((acc, f) => acc + f.tokenCount, 0);
      const totalBytes = files.reduce((acc, f) => acc + f.sizeBytes, 0);

      const cdmPayload = {
        schema_version: "1.0.0",
        source_url: sourceUrl,
        retrieved_at: now,
        total_files: files.length,
        total_tokens: totalTokens,
        total_bytes: totalBytes,
        completeness: {
          discovered_count: files.length,
          extracted_count: files.length,
          excluded_count: 0,
          failed_count: 0,
          is_complete: true,
        },
        sections: files.map((file, idx) => ({
          section_id: `sec-${idx + 1}-${file.id}`,
          original_path: file.path,
          language: file.language,
          byte_size: file.sizeBytes,
          token_count: file.tokenCount,
          body: file.content,
        })),
      };

      return JSON.stringify(cdmPayload, null, 2);
    }

    case "xml": {
      const lines = [
        `<?xml version="1.0" encoding="UTF-8"?>`,
        `<documents source="${escapeXml(sourceUrl)}" generated_at="${now}">`,
      ];

      files.forEach((file, idx) => {
        lines.push(`  <document index="${idx + 1}">`);
        lines.push(`    <source>${escapeXml(file.path)}</source>`);
        lines.push(`    <language>${escapeXml(file.language)}</language>`);
        lines.push(`    <token_count>${file.tokenCount}</token_count>`);
        lines.push(`    <document_content>`);
        lines.push(escapeXml(file.content));
        lines.push(`    </document_content>`);
        lines.push(`  </document>`);
      });

      lines.push(`</documents>`);
      return lines.join("\n");
    }

    case "txt": {
      const separator = "=".repeat(80);
      const subSeparator = "-".repeat(80);

      const header = [
        separator,
        `WEB-REPO-TO-AI CONTEXT EXPORT`,
        `Source: ${sourceUrl}`,
        `Generated: ${now}`,
        `Total Files: ${files.length}`,
        separator,
        ``,
      ].join("\n");

      const body = files
        .map((file) => {
          return [
            subSeparator,
            `FILE: ${file.path} [${file.language.toUpperCase()}] (~${file.tokenCount} tokens)`,
            subSeparator,
            file.content,
            ``,
          ].join("\n");
        })
        .join("\n");

      return `${header}\n${body}`;
    }

    case "jsonl": {
      return files
        .map((file, idx) => {
          return JSON.stringify({
            index: idx + 1,
            source_url: sourceUrl,
            path: file.path,
            language: file.language,
            size_bytes: file.sizeBytes,
            token_count: file.tokenCount,
            content: file.content,
          });
        })
        .join("\n");
    }
  }
}

function escapeXml(unsafe: string): string {
  return unsafe
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

